function slugify(value) {
  return value.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-");
}

function titleCase(value) {
  const acronyms = new Map([
    ["api", "API"],
    ["dpia", "DPIA"],
    ["scim", "SCIM"],
    ["soa", "SOA"],
    ["tia", "TIA"],
  ]);
  return value
    .split(/[-_\s]+/)
    .map(
      (word) =>
        acronyms.get(word.toLowerCase()) ??
        word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join(" ");
}

function collectYamlBlockLocations(
  source,
  markerPattern,
  endOffset = source.length,
) {
  const lines = source.split("\n");
  const locations = new Map();
  const markers = [];
  const boundaryLine = source.slice(0, endOffset).split("\n").length;
  let offset = 0;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    const match = line.match(markerPattern);
    if (match && offset < endOffset) {
      markers.push({ name: match[1], line: index + 1 });
    }
    offset += line.length + 1;
  }

  for (let index = 0; index < markers.length; index += 1) {
    const marker = markers[index];
    const nextLine = markers[index + 1]?.line ?? boundaryLine + 1;
    let endLine = nextLine - 1;
    while (endLine > marker.line && lines[endLine - 1].trim() === "") {
      endLine -= 1;
    }
    locations.set(marker.name, { start: marker.line, end: endLine });
  }

  return locations;
}

function specificationLink(location) {
  if (!location) return mcpSpecificationUrl;
  return `${mcpSpecificationUrl}#L${location.start}-L${location.end}`;
}

function lineLabel(location) {
  if (!location) return "source";
  return location.start === location.end
    ? `L${location.start}`
    : `L${location.start}–L${location.end}`;
}

function withPeriod(value) {
  return /[.!?]$/.test(value) ? value : `${value}.`;
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

async function generateN8nReference() {
  const nodeRoot = join(sourceRoot, "packages/n8n-node/nodes/Probo");
  const nodePath = join(nodeRoot, "Probo.node.ts");
  const nodeSource = await readFile(nodePath, "utf8");
  const resourceSection = nodeSource.slice(
    nodeSource.indexOf("displayName: 'Resource'"),
    nodeSource.indexOf("default: 'execute'"),
  );
  const resourcePattern =
    /\{\s*name: '([^']+)',\s*value: '([^']+)',\s*description: '([^']+)'/g;
  const resources = [];

  for (const match of resourceSection.matchAll(resourcePattern)) {
    const resource = {
      name: match[1],
      value: match[2],
      description: match[3],
      operations: [],
    };
    const indexPath = join(nodeRoot, "actions", resource.value, "index.ts");
    const indexSource = await readFile(indexPath, "utf8");
    const operationSection = indexSource.slice(
      indexSource.indexOf("name: 'operation'"),
      indexSource.indexOf("default:"),
    );
    const operationPattern =
      /\{\s*name: '([^']+)',\s*value: '([^']+)',\s*description: '([^']+)',\s*action: '([^']+)'/g;

    for (const operationMatch of operationSection.matchAll(operationPattern)) {
      const operationFile = operationSourceFile(indexSource, operationMatch[2]);
      resource.operations.push({
        name: operationMatch[1],
        value: operationMatch[2],
        description: operationMatch[3],
        source: `https://github.com/getprobo/probo/blob/main/packages/n8n-node/nodes/Probo/actions/${resource.value}/${operationFile}`,
      });
    }

    if (resource.operations.length === 0) {
      throw new Error(`No n8n operations found for ${resource.value}`);
    }
    resources.push(resource);
  }

  if (resources.length === 0) {
    throw new Error(`No n8n resources found in ${nodePath}`);
  }

  const operationCount = resources.reduce(
    (total, resource) => total + resource.operations.length,
    0,
  );
  const indexBody = [
    "---",
    "title: n8n resource reference",
    `description: Reference for ${operationCount} operations available in the Probo n8n action node, covering resources, fields, and links to the node source`,
    "---",
    "",
    "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
    "",
    `The **Probo** action node provides **${operationCount} operations** across **${resources.length} resources**. This catalog is generated from the node definitions in the Probo repository, so resource names and operation descriptions match the installed node.`,
    "",
    `Use a dedicated operation when one is available. It provides typed fields in the n8n editor and handles the expected GraphQL request and response. Use the [Execute resource](/docs/developers/api/n8n/resources/execute) only when the action node does not expose the capability you need.`,
    "",
    `The reference documents the current source on the Probo \`main\` branch. Your installed package can differ; check the node version in n8n and [review the package source](${n8nSourceUrl}) when behavior does not match.`,
    "",
    ...resources.flatMap((resource) => [
      `- [${resource.name}](/docs/developers/api/n8n/resources/${slugify(resource.name)}) — ${operationLabel(resource.operations.length)}`,
      "",
    ]),
  ].join("\n");

  await writeGenerated(
    join(docsRoot, "api/n8n/resources/index.mdx"),
    `${indexBody}\n`,
  );

  const expectedPaths = new Set(["index.mdx"]);
  for (const resource of resources) {
    const filename = `${slugify(resource.name)}.mdx`;
    const additionalContent =
      resource.value === "execute"
        ? (
            await readFile(
              join(root, "tools/reference-content/n8n-execute.mdx"),
              "utf8",
            )
          ).trim()
        : "";
    expectedPaths.add(filename);
    const resourceBody = [
      "---",
      `title: ${resource.name} n8n operations`,
      `description: Reference for ${operationLabel(resource.operations.length)} for the Probo n8n ${resource.name} resource, including field descriptions and links to the node implementation source`,
      "---",
      "",
      "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
      "",
      `${withPeriod(resource.description)} Select **${resource.name}** in the Probo node's **Resource** field.`,
      "",
      "Return to the [complete n8n resource reference](/docs/developers/api/n8n/resources) to browse another resource.",
      "",
      "| Operation | Value | Description | Source |",
      "| --- | --- | --- | --- |",
      ...resource.operations.map(
        (operation) =>
          `| ${escapeTable(operation.name)} | \`${escapeTable(operation.value)}\` | ${escapeProse(withPeriod(operation.description))} | [View implementation](${operation.source}) |`,
      ),
      "",
      additionalContent,
      "",
    ].join("\n");

    await writeGenerated(
      join(docsRoot, `api/n8n/resources/${filename}`),
      `${resourceBody}\n`,
    );
  }

  await removeStaleGeneratedFiles(
    join(docsRoot, "api/n8n/resources"),
    expectedPaths,
  );

  return resources.map((resource) => ({
    label: resource.name,
    slug: `docs/developers/api/n8n/resources/${slugify(resource.name)}`,
  }));
}

function operationLabel(count) {
  return `${count} operation${count === 1 ? "" : "s"}`;
}

function operationSourceFile(indexSource, operationValue) {
  const exportPattern = new RegExp(
    `(\\w+)Op\\s+as\\s+${operationValue}(?:[,\\s]|$)`,
  );
  const exportMatch = indexSource.match(exportPattern);
  const importName =
    exportMatch?.[1] ??
    indexSource.match(
      new RegExp(
        `import \\* as (\\w+)Op from './${operationValue.replaceAll(
          /[.*+?^${}()|[\]\\]/g,
          "\\$&",
        )}\\.operation'`,
      ),
    )?.[1];
  if (!importName) return `${operationValue}.operation.ts`;
  const importMatch = indexSource.match(
    new RegExp(`import \\* as ${importName}Op from './([^']+\\.operation)'`),
  );
  return `${importMatch?.[1] ?? operationValue}.ts`;
}

function escapeTable(value) {
  return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

// Curly braces are only safe to leave unescaped inside a backtick code span
// (e.g. a `{name}` path placeholder); MDX parses them as JS expressions
// anywhere else, so prose pulled from Go doc comments must escape them.
function escapeProse(value) {
  return escapeTable(value).replaceAll("{", "\\{").replaceAll("}", "\\}");
}
