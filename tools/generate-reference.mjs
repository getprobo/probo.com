async function generateConfigurationReference() {
  const configRoot = join(sourceRoot, "pkg/probodconfig");
  const files = (await collectFiles(configRoot, ".go")).filter(
    (file) => !file.endsWith("_test.go"),
  );
  const structs = new Map();

  for (const file of files) {
    const source = await readFile(file, "utf8");
    for (const definition of parseGoStructs(source, file)) {
      if (structs.has(definition.name)) {
        throw new Error(`Duplicate Go struct ${definition.name}`);
      }
      structs.set(definition.name, definition);
    }
  }

  if (!structs.has("FullConfig")) {
    throw new Error(`FullConfig not found in ${configRoot}`);
  }

  const fields = expandConfigStruct(structs, "FullConfig");
  const connectorVariants = [
    ["OAuth 2.0", "ConnectorConfigOAuth2"],
    ["Managed API key", "ConnectorConfigAPIKey"],
    ["GitHub App", "ConnectorConfigGitHubApp"],
  ].flatMap(([variant, type]) =>
    expandConfigStruct(structs, type, "probod.connectors[].config").map(
      (field) => ({ ...field, variant }),
    ),
  );
  const documentedSources = new Set(
    [...fields, ...connectorVariants].map((field) => field.source),
  );
  const undocumentedFields = [...structs.values()].flatMap((definition) =>
    definition.fields.filter(
      (field) =>
        !nestedConfigType(field.type, structs) &&
        !documentedSources.has(field.source),
    ),
  );
  if (undocumentedFields.length > 0) {
    throw new Error(
      `Configuration fields are not reachable from FullConfig: ${undocumentedFields.map((field) => field.goName).join(", ")}`,
    );
  }
  const groups = Map.groupBy(fields, configGroup);
  const fieldCount = fields.length + connectorVariants.length;
  const body = [
    "---",
    "title: Configuration file reference",
    `description: Complete reference for all ${fieldCount} probod JSON and YAML configuration fields, covering type, defaults, and environment variable overrides`,
    "---",
    "",
    "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
    "",
    `This reference documents **${fieldCount} fields** accepted by the current \`probod\` configuration schema. It is generated from [\`pkg/probodconfig\`](https://github.com/getprobo/probo/tree/main/pkg/probodconfig), so every serialized field is included.`,
    "",
    "JSON and YAML use the same field names and hierarchy. Array paths use `[]`; map paths use `{name}` to represent a user-defined key.",
    "",
    "The serialization column describes whether an empty value can be omitted from generated files. It does not by itself indicate whether a value is operationally required.",
    "",
    ...[...groups.entries()].flatMap(([group, entries]) =>
      referenceFieldTable(group, entries),
    ),
    "## Connector configuration variants",
    "",
    "`probod.connectors[].config` depends on the connector protocol:",
    "",
    "| Variant | Field | Type | Serialization | Source |",
    "| --- | --- | --- | --- | --- |",
    ...connectorVariants.map(
      (field) =>
        `| ${field.variant} | \`${escapeTable(field.path)}\` | ${escapeTable(field.type)} | ${field.omittedWhenEmpty ? "Omitted when empty" : "Always emitted"} | [View field](${field.source}) |`,
    ),
    "",
    "Connector `settings` is a provider-specific object and therefore has no fixed set of child fields in the shared configuration schema.",
    "",
  ].join("\n");

  await writeGenerated(
    join(configurationDocsRoot, "config-reference.mdx"),
    `${body}\n`,
  );
}

function parseGoStructs(source, file) {
  const lines = source.split("\n");
  const definitions = [];

  for (let index = 0; index < lines.length; index += 1) {
    const match = lines[index].match(
      /^\s*(?:type\s+)?([A-Za-z0-9_]+)\s+struct\s*\{\s*$/,
    );
    if (!match) continue;

    const fields = [];
    let comments = [];
    for (index += 1; index < lines.length; index += 1) {
      const line = lines[index];
      if (line.trim() === "}") break;
      const comment = line.match(/^\s*\/\/\s?(.*)$/);
      if (comment) {
        comments.push(comment[1]);
        continue;
      }
      if (line.trim() === "") {
        comments = [];
        continue;
      }

      const field = line.match(
        /^\s*([A-Za-z0-9_]+)\s+(.+?)\s+`json:"([^"]+)"`(?:\s*\/\/\s?(.*))?$/,
      );
      if (!field) {
        if (line.includes('json:"')) {
          throw new Error(
            `Cannot parse JSON field at ${relative(root, file)}:${index + 1}`,
          );
        }
        comments = [];
        continue;
      }

      const [jsonName, ...options] = field[3].split(",");
      if (jsonName !== "-") {
        fields.push({
          goName: field[1],
          type: field[2].trim(),
          jsonName,
          omittedWhenEmpty:
            options.includes("omitempty") || options.includes("omitzero"),
          description: field[4] ?? comments.join(" "),
          source: goSourceLink(file, index + 1),
        });
      }
      comments = [];
    }

    definitions.push({ name: match[1], fields });
  }

  return definitions;
}

function expandConfigStruct(structs, typeName, prefix = "") {
  const definition = structs.get(typeName);
  if (!definition) throw new Error(`Unknown configuration struct ${typeName}`);

  return definition.fields.flatMap((field) => {
    const path = prefix ? `${prefix}.${field.jsonName}` : field.jsonName;
    const nested = nestedConfigType(field.type, structs);
    if (!nested) {
      return [
        {
          ...field,
          path,
          type: configTypeLabel(field.type),
        },
      ];
    }

    const nestedPath = `${path}${nested.pathSuffix}`;
    return expandConfigStruct(structs, nested.typeName, nestedPath);
  });
}

function nestedConfigType(type, structs) {
  const value = type.replace(/^\*/, "");
  if (structs.has(value)) return { typeName: value, pathSuffix: "" };

  const slice = value.match(/^\[\]\*?([A-Za-z0-9_]+)$/);
  if (slice && structs.has(slice[1])) {
    return { typeName: slice[1], pathSuffix: "[]" };
  }

  const map = value.match(/^map\[string\]\*?([A-Za-z0-9_]+)$/);
  if (map && structs.has(map[1])) {
    return { typeName: map[1], pathSuffix: ".{name}" };
  }

  return null;
}

function configTypeLabel(type) {
  const value = type.replace(/^\*/, "");
  if (value === "bool") return "boolean";
  if (/^(?:u?int(?:8|16|32|64)?|time\.Duration)$/.test(value)) {
    return "integer";
  }
  if (/^float(?:32|64)$/.test(value)) return "number";
  if (value === "any" || value.startsWith("map[")) return "object";
  if (value.startsWith("[]")) {
    return `${configTypeLabel(value.slice(2))}[]`;
  }
  return value;
}

function configGroup(field) {
  const parts = field.path.split(".");
  if (parts[0] === "unit") return "Unit";
  if (parts[0] !== "probod" || parts.length === 2) return "Core application";
  const name = parts[1].replace(/\[\]$/, "");
  return (
    new Map([
      ["api", "API"],
      ["aws", "Object storage"],
      ["esign", "Electronic signatures"],
      ["itam", "ITAM"],
      ["llm", "AI providers and agents"],
      ["pg", "PostgreSQL"],
      ["trust-center", "Compliance portal"],
    ]).get(name) ?? titleCase(name)
  );
}

function referenceFieldTable(group, fields) {
  return [
    `## ${group}`,
    "",
    "| Field | Type | Serialization | Description | Source |",
    "| --- | --- | --- | --- | --- |",
    ...fields.map(
      (field) =>
        `| \`${escapeTable(field.path)}\` | ${escapeTable(field.type)} | ${field.omittedWhenEmpty ? "Omitted when empty" : "Always emitted"} | ${escapeProse(field.description || "—")} | [View field](${field.source}) |`,
    ),
    "",
  ];
}

async function generateEnvironmentReference() {
  const bootstrapRoot = join(sourceRoot, "pkg/bootstrap");
  const files = (await collectFiles(bootstrapRoot, ".go")).filter(
    (file) => !file.endsWith("_test.go"),
  );
  const occurrences = new Map();
  const sources = new Map();

  for (const file of files) {
    const source = await readFile(file, "utf8");
    sources.set(file, source);
    const lines = source.split("\n");
    for (let index = 0; index < lines.length; index += 1) {
      for (const match of lines[index].matchAll(/"(PROBOD_[A-Z0-9_]+)"/g)) {
        if (match[1].endsWith("_")) continue;
        if (!occurrences.has(match[1])) {
          occurrences.set(match[1], {
            file,
            line: index + 1,
          });
        }
      }
    }
  }

  const builderPath = join(bootstrapRoot, "builder.go");
  const builderSource = sources.get(builderPath);
  if (!builderSource) throw new Error(`Missing ${builderPath}`);
  const providerRoot = join(sourceRoot, "pkg/connector/provider");
  const builtinProviderSource = await readFile(
    join(providerRoot, "builtin.go"),
    "utf8",
  );
  const connectorProviderSource = await readFile(
    join(sourceRoot, "pkg/coredata/connector_provider.go"),
    "utf8",
  );
  addDynamicConnectorVariables(
    occurrences,
    builderSource,
    builderPath,
    builtinProviderSource,
    connectorProviderSource,
  );

  const required = new Set([
    "PROBOD_ENCRYPTION_KEY",
    "PROBOD_AUTH_COOKIE_SECRET",
    "PROBOD_AUTH_PASSWORD_PEPPER",
    "PROBOD_OAUTH2_SERVER_SIGNING_KEY",
  ]);
  const variables = [...occurrences.entries()]
    .map(([name, location]) => {
      const usage = environmentUsage(name, sources);
      return {
        name,
        type: usage.type,
        defaultValue: usage.defaultValue,
        requirement: required.has(name)
          ? "Required"
          : conditionalEnvironmentVariable(name)
            ? "Conditional"
            : "Optional",
        source: goSourceLink(location.file, location.line),
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name));
  const groups = Map.groupBy(variables, environmentGroup);
  const body = [
    "---",
    "title: Environment variable reference",
    "description: Complete reference for all PROBOD_* environment variables, covering defaults and how each one maps to a probod config field",
    "---",
    "",
    "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
    "",
    "This reference documents the `PROBOD_*` variables read by the current `probod-bootstrap` implementation. It is generated from [`pkg/bootstrap`](https://github.com/getprobo/probo/tree/main/pkg/bootstrap), including dynamically constructed connector variables.",
    "",
    "A dash in the default column means the variable has no bootstrap default. Optional variables without a default are rendered as an empty value when unset. Conditional connector values become required when the matching connector client ID is set.",
    "",
    ...[...groups.entries()].flatMap(([group, entries]) => [
      `## ${group}`,
      "",
      "| Variable | Type | Default | Requirement | Source |",
      "| --- | --- | --- | --- | --- |",
      ...entries.map(
        (variable) =>
          `| \`${variable.name}\` | ${variable.type} | ${variable.defaultValue ?? "—"} | ${variable.requirement} | [View usage](${variable.source}) |`,
      ),
      "",
    ]),
  ].join("\n");

  await writeGenerated(
    join(configurationDocsRoot, "environment-reference.mdx"),
    `${body}\n`,
  );
}

function addDynamicConnectorVariables(
  occurrences,
  source,
  file,
  builtinProviderSource,
  connectorProviderSource,
) {
  const lines = source.split("\n");
  const providerPattern =
    /\{"(CONNECTOR_[A-Z0-9_]+)",\s*\[\]string\{([^}]*)\}\}/g;

  for (const match of source.matchAll(providerPattern)) {
    const line = source.slice(0, match.index).split("\n").length;
    const suffixes = [
      "CLIENT_ID",
      ...[...match[2].matchAll(/"([A-Z0-9_]+)"/g)].map((suffix) => suffix[1]),
    ];
    for (const suffix of suffixes) {
      const name = `PROBOD_${match[1]}_${suffix}`;
      if (!occurrences.has(name)) occurrences.set(name, { file, line });
    }
  }

  const loop = source.match(
    /for _, provider := range \[\]string\{([\s\S]*?)\}\s*\{/,
  );
  if (!loop) throw new Error("Cannot find dynamic connector provider list");
  const line = source.slice(0, loop.index).split("\n").length;
  for (const provider of loop[1].matchAll(/"([A-Z0-9_]+)"/g)) {
    for (const suffix of ["CLIENT_ID", "CLIENT_SECRET"]) {
      const name = `PROBOD_CONNECTOR_${provider[1]}_${suffix}`;
      if (!occurrences.has(name)) occurrences.set(name, { file, line });
    }
  }

  const providerValues = new Map(
    [
      ...connectorProviderSource.matchAll(
        /ConnectorProvider([A-Za-z0-9]+)\s+ConnectorProvider\s*=\s*"([A-Z0-9_]+)"/g,
      ),
    ].map((match) => [match[1], match[2]]),
  );
  const builtinProviders = builtinProviderSource.match(
    /for _, reg := range \[\]\*Registration\{([\s\S]*?)\}\s*\{/,
  );
  if (!builtinProviders) throw new Error("Cannot find builtin provider list");
  const endpointFields = source.match(
    /connectorEndpointFields\s*=\s*\[\]string\{([^}]*)\}/,
  );
  if (!endpointFields) throw new Error("Cannot find connector endpoint fields");
  const endpointLine = source
    .slice(0, source.indexOf('"PROBOD_CONNECTOR_" + string(r.Provider)'))
    .split("\n").length;
  const fields = [...endpointFields[1].matchAll(/"([A-Z0-9_]+)"/g)].map(
    (match) => match[1],
  );
  for (const registration of builtinProviders[1].matchAll(
    /([a-z][A-Za-z0-9]+)Registration\(\)/g,
  )) {
    const providerName =
      registration[1][0].toUpperCase() + registration[1].slice(1);
    const provider = [...providerValues].find(
      ([name]) => name.toLowerCase() === providerName.toLowerCase(),
    )?.[1];
    if (!provider) {
      throw new Error(`Cannot resolve connector provider ${providerName}`);
    }
    for (const field of fields) {
      const name = `PROBOD_CONNECTOR_${provider}_ENDPOINT_${field}`;
      if (!occurrences.has(name)) {
        occurrences.set(name, { file, line: endpointLine });
      }
    }
  }

  const unresolved = lines
    .map((value, index) => ({ value, line: index + 1 }))
    .filter(({ value }) => /"PROBOD_[A-Z0-9_]*"\s*\+/.test(value));
  if (unresolved.length !== 5) {
    throw new Error(
      `Expected five dynamic PROBOD variable expressions in ${file}, found ${unresolved.length}`,
    );
  }
}

function environmentUsage(name, sources) {
  for (const source of sources.values()) {
    const escaped = name.replaceAll(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const call = source.match(
      new RegExp(
        `getEnv([A-Za-z]*)(?:OrDefault)?\\(\\s*"${escaped}"(?:,\\s*([^\\)]+))?\\)`,
      ),
    );
    if (!call) continue;

    const method = call[1];
    const type = method.includes("Bool")
      ? "boolean"
      : method.includes("Int")
        ? "integer"
        : method.includes("Float")
          ? "number"
          : new RegExp(
                `parseOriginsList\\(\\s*b\\.resolver\\.getEnv\\(\\s*"${escaped}"\\s*\\)\\s*,?\\s*\\)`,
              ).test(source)
            ? "comma-separated list"
            : "string";
    const hasDefault = call[0].includes("OrDefault");
    return {
      type,
      defaultValue: hasDefault
        ? `\`${call[2]?.trim().replace(/,$/, "")}\``
        : null,
    };
  }

  return { type: "string", defaultValue: null };
}

function conditionalEnvironmentVariable(name) {
  return (
    name.startsWith("PROBOD_CONNECTOR_") &&
    (name.endsWith("_CLIENT_SECRET") ||
      name.endsWith("_SIGNING_SECRET") ||
      name.endsWith("_INTEGRATION_SLUG"))
  );
}

function environmentGroup(variable) {
  const name = variable.name;
  const groups = [
    ["API", "PROBOD_API_"],
    ["PostgreSQL", "PROBOD_PG_"],
    ["Authentication", "PROBOD_AUTH_"],
    ["SAML", "PROBOD_SAML_"],
    ["OAuth 2.0 server", "PROBOD_OAUTH2_"],
    ["ITAM", "PROBOD_ITAM_"],
    ["Compliance portal", "PROBOD_TRUST_CENTER_"],
    ["Object storage", "PROBOD_AWS_"],
    ["Notifications", /PROBOD_(?:MAILER|SMTP|SLACK|WEBHOOK|DOCUMENT)_/],
    ["Connectors", "PROBOD_CONNECTOR_"],
    ["AI providers and agents", /PROBOD_(?:OPENAI|ANTHROPIC|FIRECRAWL|AGENT)_/],
    [
      "Background workers",
      /PROBOD_(?:EVIDENCE_DESCRIBER|THIRD_PARTY_VETTING|TRACKER_MAPPING|COMMON_PATTERN_ENRICHMENT|COMMON_THIRD_PARTY_ENRICHMENT)_/,
    ],
    ["Custom domains", /PROBOD_(?:CUSTOM_DOMAINS|ACME)_/],
    ["SCIM bridge", "PROBOD_SCIM_BRIDGE_"],
    ["Electronic signatures", "PROBOD_ESIGN_"],
  ];
  return (
    groups.find(([, pattern]) =>
      typeof pattern === "string"
        ? name.startsWith(pattern)
        : pattern.test(name),
    )?.[0] ?? "Core application"
  );
}

function goSourceLink(file, line) {
  const sourcePath = relative(sourceRoot, file).split(sep).join("/");
  return `https://github.com/getprobo/probo/blob/main/${sourcePath}#L${line}`;
}

async function collectFiles(directory, extension) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) return collectFiles(path, extension);
      return entry.name.endsWith(extension) ? [path] : [];
    }),
  );
  return nested.flat();
}

async function writeGenerated(path, content) {
  const formattedContent = await format(content, { filepath: path });

  if (checkOnly) {
    const current = await readFile(path, "utf8");
    if (current !== formattedContent) {
      throw new Error(
        `${relative(root, path)} is stale; run npm run docs:generate`,
      );
    }
    return;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, formattedContent);
}

async function removeStaleGeneratedFiles(directory, expectedPaths) {
  const stalePaths = (await readdir(directory)).filter(
    (filename) => filename.endsWith(".mdx") && !expectedPaths.has(filename),
  );
  if (stalePaths.length > 0 && checkOnly) {
    throw new Error(
      `${relative(root, directory)} contains stale generated pages; run npm run docs:generate`,
    );
  }
  await Promise.all(
    stalePaths.map((filename) =>
      rm(join(directory, filename), { force: true }),
    ),
  );
}

