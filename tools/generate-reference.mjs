async function generateMcpReference() {
  const specificationPath = join(
    sourceRoot,
    "pkg/server/api/mcp/v1/specification.yaml",
  );
  const specification = await readFile(specificationPath, "utf8");
  const parsedSpecification = parse(specification);
  if (!Array.isArray(parsedSpecification?.tools)) {
    throw new Error(`Expected a tools array in ${specificationPath}`);
  }

  const schemaLocations = collectYamlBlockLocations(
    specification,
    /^    ([A-Za-z0-9_]+):$/,
    specification.indexOf("\ntools:\n"),
  );
  const toolLocations = collectYamlBlockLocations(
    specification,
    /^  - name: (\S+)$/,
  );
  const tools = parsedSpecification.tools.map((tool, index) =>
    normalizeMcpTool(tool, index, specificationPath, {
      schemaLocations,
      toolLocations,
    }),
  );

  if (tools.length === 0) {
    throw new Error(`No MCP tools found in ${specificationPath}`);
  }

  const categories = new Map();
  for (const tool of tools) {
    const category = categoryForTool(tool.name);
    const entries = categories.get(category) ?? [];
    entries.push(tool);
    categories.set(category, entries);
  }

  const indexBody = [
    "---",
    "title: MCP tool reference",
    `description: Complete reference for all ${tools.length} MCP tools available in Probo, covering input schemas, output schemas, and behavior hints for AI agent integrations`,
    "---",
    "",
    "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
    "",
    `Probo exposes **${tools.length} MCP tools**. This catalog is generated from the MCP specification in the Probo repository, so names and behavior hints match the server implementation.`,
    "",
    `Every tool links to its input schema, output schema, and declaration in the canonical [\`specification.yaml\`](${mcpSpecificationUrl}). A client discovers these JSON schemas during MCP initialization.`,
    "",
    "## Behavior hints",
    "",
    "- **Read only** tools do not change Probo data.",
    "- **Destructive** tools can permanently remove data or end an active process.",
    "- **Idempotent** tools can be repeated with the same input without an additional effect.",
    "- **Open world** tools can interact with external entities outside Probo.",
    "",
    ...[...categories.entries()].flatMap(([category, entries]) => [
      `- [${category}](/docs/developers/api/mcp/tools/catalog/${slugify(category)}) — ${entries.length} tools`,
      "",
    ]),
  ].join("\n");

  await writeGenerated(
    join(docsRoot, "api/mcp/tools/index.mdx"),
    `${indexBody}\n`,
  );

  const expectedPaths = new Set();
  for (const [category, entries] of categories) {
    const filename = `${slugify(category)}.mdx`;
    expectedPaths.add(filename);
    const categoryBody = [
      "---",
      `title: ${category} MCP tools`,
      `description: Browse all ${entries.length} Probo MCP tools for ${category.toLowerCase()}, with input schemas, output schemas, and behavior hints for building AI agent integrations`,
      "---",
      "",
      "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
      "",
      `This page documents **${entries.length} tools** in the ${category.toLowerCase()} group. Return to the [complete MCP tool reference](/docs/developers/api/mcp/tools) to browse another group.`,
      "",
      "Select a tool to inspect its schemas and behavior. Schema links open the exact definition in GitHub.",
      "",
      '<ol className="mcp-tool-list">',
      ...entries.flatMap(toolReference),
      "</ol>",
    ].join("\n");

    await writeGenerated(
      join(docsRoot, `api/mcp/tools/catalog/${filename}`),
      `${categoryBody}\n`,
    );
  }

  await removeStaleGeneratedFiles(
    join(docsRoot, "api/mcp/tools/catalog"),
    expectedPaths,
  );
  await removeStaleGeneratedFiles(
    join(docsRoot, "api/mcp/tools"),
    new Set(["index.mdx"]),
  );
  await updateMcpOverviewToolCount(tools.length);

  return [...categories.keys()]
    .sort((left, right) => left.localeCompare(right))
    .map((category) => ({
      label: category,
      slug: `docs/developers/api/mcp/tools/catalog/${slugify(category)}`,
    }));
}

async function updateMcpOverviewToolCount(toolCount) {
  const path = join(docsRoot, "api/mcp/overview.mdx");
  const current = await readFile(path, "utf8");
  const descriptionPattern = /the \d+ available tools/;
  const bodyPattern = /exposes \*\*\d+ tools\*\*/;

  if (!descriptionPattern.test(current) || !bodyPattern.test(current)) {
    throw new Error(
      `${relative(root, path)} is missing the MCP tool-count phrasing expected by docs:generate`,
    );
  }

  const updated = current
    .replace(descriptionPattern, `the ${toolCount} available tools`)
    .replace(bodyPattern, `exposes **${toolCount} tools**`);

  if (checkOnly) {
    if (updated !== current) {
      throw new Error(
        `${relative(root, path)} is stale; run npm run docs:generate`,
      );
    }
    return;
  }

  if (updated !== current) {
    await writeFile(path, updated);
  }
}

function normalizeMcpTool(tool, index, specificationPath, locations) {
  const path = `tools[${index}]`;
  for (const field of ["name", "title", "description"]) {
    if (typeof tool?.[field] !== "string" || tool[field].length === 0) {
      throw new Error(
        `${specificationPath}: ${path}.${field} must be a string`,
      );
    }
  }

  const inputReference = tool.inputSchema?.$ref;
  const outputReference = tool.outputSchema?.$ref;
  if (
    typeof inputReference !== "string" ||
    typeof outputReference !== "string"
  ) {
    throw new Error(
      `${specificationPath}: ${path} must define inputSchema.$ref and outputSchema.$ref`,
    );
  }

  const input = inputReference.split("/").at(-1);
  const output = outputReference.split("/").at(-1);
  const hints = tool.hints ?? {};
  return {
    name: tool.name,
    title: tool.title,
    description: tool.description,
    readonly: Boolean(hints.readonly),
    destructive: Boolean(hints.destructive),
    idempotent: Boolean(hints.idempotent),
    openWorld: Boolean(hints.openWorld),
    input,
    output,
    sourceLocation: locations.toolLocations.get(tool.name),
    inputLocation: locations.schemaLocations.get(input),
    outputLocation: locations.schemaLocations.get(output),
  };
}

function toolReference(tool, index) {
  const sourceLink = specificationLink(tool.sourceLocation);
  const inputLink = specificationLink(tool.inputLocation);
  const outputLink = specificationLink(tool.outputLocation);
  const writeLabel = tool.readonly ? "Read only" : "Writes data";

  return [
    "  <li>",
    `    <details className="mcp-tool" id="${escapeHtml(tool.name)}"${index === 0 ? " open" : ""}>`,
    "      <summary>",
    '        <span className="mcp-tool__identity">',
    `          <code>${escapeHtml(tool.name)}</code>`,
    `          <span>${escapeHtml(tool.title)}</span>`,
    "        </span>",
    `        <span className="mcp-tool__mode">${writeLabel}</span>`,
    "      </summary>",
    '      <div className="mcp-tool__body">',
    `        <p className="mcp-tool__description">${escapeHtml(withPeriod(tool.description))}</p>`,
    '        <dl className="mcp-tool__meta">',
    schemaReference("Input", tool.input, inputLink),
    schemaReference("Output", tool.output, outputLink),
    "          <div>",
    "            <dt>Behavior</dt>",
    `            <dd>${behaviorSummary(tool)}</dd>`,
    "          </div>",
    "          <div>",
    "            <dt>Source</dt>",
    `            <dd><a href="${sourceLink}">specification.yaml · ${lineLabel(tool.sourceLocation)} ↗</a></dd>`,
    "          </div>",
    "        </dl>",
    "      </div>",
    "    </details>",
    "  </li>",
  ];
}

function schemaReference(label, name, link) {
  return [
    "          <div>",
    `            <dt>${label}</dt>`,
    `            <dd><a href="${link}"><code>${escapeHtml(name)}</code></a></dd>`,
    "          </div>",
  ].join("\n");
}

function behaviorSummary(tool) {
  return [
    tool.readonly ? "Read only" : "Writes data",
    tool.destructive ? "Destructive" : "Non-destructive",
    tool.idempotent ? "Idempotent" : "Non-idempotent",
    tool.openWorld ? "Open world" : "Closed world",
  ].join(" · ");
}

async function generateCliReference() {
  const commandRoot = join(sourceRoot, "pkg/cmd");
  const files = await collectFiles(commandRoot, ".go");
  const commands = [];
  const directoryNames = new Map();
  const cliSourceUrl = "https://github.com/getprobo/probo/blob/main/pkg/cmd";

  for (const file of files) {
    const path = relative(commandRoot, file).split(sep);
    if (path[0] === "root") continue;
    const command = await commandFromFile(file);
    if (!command) continue;
    const directory = path.slice(0, -1).join("/");
    const fileKey = basename(file, ".go").replaceAll(/[-_]/g, "");
    const directoryKey = basename(directory).replaceAll(/[-_]/g, "");
    if (fileKey === directoryKey) {
      directoryNames.set(directory, command.use.split(/\s+/, 1)[0]);
    }
  }

  for (const file of files) {
    const path = relative(commandRoot, file).split(sep);
    if (path[0] === "root" || path.some((part) => part.endsWith("_test.go"))) {
      continue;
    }

    const command = await commandFromFile(file);
    if (!command) continue;

    const directories = path.slice(0, -1);
    const namedDirectories = directories.flatMap((directory, index) => {
      const key = directories.slice(0, index + 1).join("/");
      const name = directoryNames.get(key);
      return name ? [name] : [];
    });
    const rootName = namedDirectories[0];
    const commandName = command.use.split(/\s+/, 1)[0];
    const pathParts = namedDirectories;
    if (pathParts.at(-1) !== commandName) pathParts.push(commandName);

    commands.push({
      group: rootName,
      path: `prb ${pathParts.join(" ")}`,
      usage: command.use,
      description: command.short,
      source: `${cliSourceUrl}/${relative(commandRoot, file).split(sep).join("/")}`,
    });
  }

  const uniqueCommands = [
    ...new Map(commands.map((command) => [command.path, command])).values(),
  ].sort((a, b) => a.path.localeCompare(b.path));
  const groups = Map.groupBy(uniqueCommands, (command) => command.group);

  const body = [
    "---",
    "title: CLI command reference",
    `description: Complete reference for ${groups.size} top-level prb commands — the Probo CLI you use to manage compliance programs directly from the terminal`,
    "---",
    "",
    "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
    "",
    `The \`prb\` CLI provides **${groups.size} top-level commands**. This catalog is generated from the Cobra command definitions in the Probo repository, so command names, summaries, and usage match the current source.`,
    "",
    "Your installed version can differ from the current source. Run `prb <command> --help` for its flags, accepted values, and examples.",
    "",
    ...[...groups.entries()].flatMap(([group, entries]) => [
      `- [\`prb ${group}\`](/docs/developers/cli/commands/${slugify(group)}) — ${withPeriod(entries[0].description)} ${commandLabel(entries.length)}`,
      "",
    ]),
  ].join("\n");

  await writeGenerated(join(docsRoot, "cli/commands/index.mdx"), `${body}\n`);

  const expectedPaths = new Set(["index.mdx"]);
  for (const [group, entries] of groups) {
    const filename = `${slugify(group)}.mdx`;
    expectedPaths.add(filename);
    const groupBody = [
      "---",
      `title: prb ${group} command reference`,
      `description: Command reference for ${commandLabel(entries.length)} under prb ${group}, showing full usage, accepted flags, and a link to the exact CLI implementation source`,
      "---",
      "",
      "{/* Generated by tools/generate-reference.mjs. Do not edit manually. */}",
      "",
      `${withPeriod(entries[0].description)} This page documents **${commandLabel(entries.length)}** under \`prb ${group}\`.`,
      "",
      "Run any command with `--help` to inspect the flags, accepted values, and examples provided by your installed version. Return to the [complete CLI command reference](/docs/developers/cli/commands) to browse another command.",
      "",
      "| Command | Description | Usage | Source |",
      "| --- | --- | --- | --- |",
      ...entries.map(
        (command) =>
          `| \`${escapeTable(command.path)}\` | ${escapeProse(withPeriod(command.description))} | \`${escapeTable(usageFor(command))}\` | [View implementation](${command.source}) |`,
      ),
      "",
    ].join("\n");

    await writeGenerated(
      join(docsRoot, `cli/commands/${filename}`),
      `${groupBody}\n`,
    );
  }

  await removeStaleGeneratedFiles(
    join(docsRoot, "cli/commands"),
    expectedPaths,
  );

  return [...groups.keys()].map((group) => ({
    label: titleCase(group),
    slug: `docs/developers/cli/commands/${slugify(group)}`,
  }));
}

async function commandFromFile(file) {
  const source = await readFile(file, "utf8");
  const match = source.match(
    /&cobra\.Command\{[\s\S]*?\bUse:\s*"([^"]+)"[\s\S]*?\bShort:\s*"([^"]+)"/,
  );
  return match ? { use: match[1], short: match[2] } : null;
}

function usageFor(command) {
  const suffix = command.usage.split(/\s+/).slice(1).join(" ");
  return suffix ? `${command.path} ${suffix}` : command.path;
}

function commandLabel(count) {
  return `${count} command${count === 1 ? "" : "s"}`;
}

